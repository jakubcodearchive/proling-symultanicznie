  <div class="faq-list">

    <div class="faq-item">
      <h3 class="headline headline--small">
        Czym różni się tłumaczenie symultaniczne od konsekutywnego?
      </h3>
      <p>
        Jeśli pojawiają się wątpliwości — już wyjaśniamy.
        Tłumaczenie symultaniczne polega na przekładzie wypowiedzi na bieżąco,
        zazwyczaj w kabinie, dzięki czemu uczestnicy wydarzenia słyszą
        tłumaczenie bez przerw. W tłumaczeniu konsekutywnym tłumacz
        zabiera głos po prelegencie, co pozwala na dokładniejsze
        opracowanie przekładu, ale może nieco wydłużyć przebieg spotkania.
      </p>
    </div>

    <div class="faq-item">
      <h3 class="headline headline--small">
        Kiedy warto wybrać tłumaczenie symultaniczne?
      </h3>
      <p>
        Tłumaczenie symultaniczne rekomendujemy podczas wydarzeń
        o większej skali — konferencji, kongresów, debat branżowych
        oraz paneli z udziałem gości zagranicznych.
        Pozwala ono zachować tempo programu oraz komfort komunikacji
        uczestników, co jest szczególnie istotne przy wydarzeniach
        organizowanych w Szczecinie i regionie.
      </p>
    </div>

    <div class="faq-item">
      <h3 class="headline headline--small">
        Czy zapewniacie sprzęt do tłumaczeń symultanicznych?
      </h3>
      <p>
        Tak. Zapewniamy kompletne zaplecze techniczne, obejmujące
        kabiny tłumaczeniowe, systemy słuchawkowe, mikrofony,
        nagłośnienie oraz obsługę techniczną wydarzeń.
        Dzięki temu organizatorzy mogą liczyć na stabilną
        i profesjonalną realizację konferencji.
      </p>
    </div>

    <div class="faq-item">
      <h3 class="headline headline--small">
        Jak wygląda wycena tłumaczenia symultanicznego?
      </h3>
      <p>
        Wycena uzależniona jest od liczby języków, czasu trwania wydarzenia,
        tematyki oraz zapotrzebowania na sprzęt konferencyjny.
        Każdy projekt wyceniamy indywidualnie na podstawie
        krótkiego opisu wydarzenia i jego lokalizacji.
      </p>
    </div>

    <div class="faq-item">
      <h3 class="headline headline--small">
        Czy realizujecie tłumaczenia online?
      </h3>
